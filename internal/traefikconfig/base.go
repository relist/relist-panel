// Package traefikconfig owns Traefik's static config: an embedded base, the
// operator's Traefik override merged over it, and the Traefik apply that
// writes the result and restarts Traefik with self-heal (ADR-0030).
package traefikconfig

import _ "embed"

//go:embed base.yml
var baseYAML []byte

//go:embed accesslog.yml
var accessLogYAML []byte

// GeneratedHeader is the first line of the generated traefik.yml.
const GeneratedHeader = "# Generated by relist-panel from its base and traefik.override.yml. Do not edit: changes are overwritten."

// Base is the embedded base, without the conditional accessLog section.
func Base() []byte { return baseYAML }
